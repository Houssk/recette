// Test d'isolation RLS V1 : ce qu'un visiteur anonyme (clé publishable) peut et ne peut pas faire.
import { createClient } from "@supabase/supabase-js";
import { randomUUID } from "node:crypto";
const url = process.env.NEXT_PUBLIC_SUPABASE_URL, key = process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY;
const db = createClient(url, key, { auth: { persistSession: false } });
const r = [];
const ok = (nom, cond, detail = "") => r.push({ nom, resultat: cond ? "RÉUSSI" : "ÉCHOUÉ", detail });

const id = randomUUID();
const base = { id, titre: "Test RLS automatique", gravite: "mineure", etapes: "1", attendu: "a", obtenu: "b", auteur: "test-rls" };
let e = (await db.from("anomalies").insert(base)).error;
ok("anon peut créer une anomalie", !e, e?.message);
e = (await db.from("anomalies").insert({ ...base, id: randomUUID(), statut: "verifiee" })).error;
ok("anon ne peut pas créer directement en « Vérifiée »", !!e, e?.message);
const { data: h } = await db.from("historique").select("*").eq("anomalie_id", id);
ok("historique initial créé par trigger", h?.length === 1 && h[0].nouveau === "nouvelle");
e = (await db.from("anomalies").update({ titre: "piraté" }).eq("id", id)).error;
ok("anon ne peut pas modifier le titre", !!e, e?.message);
let { error: e2, count } = await db.from("anomalies").delete({ count: "exact" }).eq("id", id);
ok("anon ne peut pas supprimer", !!e2 || count === 0, e2?.message ?? `lignes supprimées: ${count}`);
e = (await db.rpc("changer_statut", { p_anomalie: id, p_nouveau: "verifiee", p_commentaire: null, p_auteur: "x" })).error;
ok("transition interdite Nouvelle → Vérifiée refusée", !!e, e?.message);
e = (await db.rpc("changer_statut", { p_anomalie: id, p_nouveau: "en_cours", p_commentaire: null, p_auteur: "dev" })).error;
ok("Nouvelle → En cours accepté", !e, e?.message);
await db.rpc("changer_statut", { p_anomalie: id, p_nouveau: "corrigee", p_commentaire: null, p_auteur: "dev" });
e = (await db.rpc("changer_statut", { p_anomalie: id, p_nouveau: "en_cours", p_commentaire: " ", p_auteur: "ines" })).error;
ok("rouvrir sans commentaire refusé", !!e, e?.message);
e = (await db.rpc("changer_statut", { p_anomalie: id, p_nouveau: "verifiee", p_commentaire: "OK sur iPhone", p_auteur: "ines" })).error;
ok("Corrigée → Vérifiée avec commentaire accepté", !e, e?.message);
const { data: h2 } = await db.from("historique").select("nouveau").eq("anomalie_id", id).order("cree_le");
ok("historique complet (4 lignes)", h2?.length === 4, h2?.map((x) => x.nouveau).join(" > "));
e = (await db.from("captures").insert({ anomalie_id: id, chemin: `${randomUUID()}/${randomUUID()}.jpg` })).error;
ok("capture rattachée à une autre anomalie refusée", !!e, e?.message);
const up = await db.storage.from("captures").upload(`${id}/${randomUUID()}.jpg`, new Blob([new Uint8Array([255, 216, 255])], { type: "image/jpeg" }));
ok("dépôt d'image dans le bucket accepté", !up.error, up.error?.message);
const bad = await db.storage.from("captures").upload(`autre/chemin.txt`, new Blob(["x"], { type: "text/plain" }));
ok("dépôt hors format refusé", !!bad.error, bad.error?.message);
const rm = await db.storage.from("captures").remove([up.data?.path ?? "x"]);
ok("anon ne peut pas supprimer une capture", !rm.data?.length, `supprimés: ${rm.data?.length ?? 0}`);
const pub = await fetch(`${url}/storage/v1/object/public/captures/${up.data?.path}`);
ok("bucket non public (URL publique refusée)", pub.status >= 400, `HTTP ${pub.status}`);
const { data: buckets } = await db.storage.listBuckets();
ok("anon ne liste pas les buckets", !buckets?.length, `buckets visibles: ${buckets?.length ?? 0}`);
console.table(r);
console.log(JSON.stringify({ id_test: id }));
process.exit(r.some((x) => x.resultat === "ÉCHOUÉ") ? 1 : 0);
